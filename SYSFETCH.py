import platform
import psutil
import time
SYS = platform.uname()
SYS1 = platform.python_build()
WI = platform.win32_ver()
MO = platform.mac_ver()
UX = platform.libc_ver()
LX = platform.freedesktop_os_release
PT = time.process_time()
PT2 = time.process_time_ns()
TTN = time.thread_time_ns()
CC = psutil.cpu_count()
CCL = psutil.cpu_count(logical=False)
DU = psutil.disk_usage('/')
VM = psutil.virtual_memory()
SM = psutil.swap_memory()
print("|------------|")
print("|SYSFETCH 0.5|")
print("|------------|")
print("--------------------")
print("BASIC INFO: ", SYS)
