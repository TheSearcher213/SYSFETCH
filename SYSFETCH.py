print(" SYSTEM IDENTIFIER: (IF BLANK IGNORE)")
print("Windows: ", WI)
print("Mac: ", MO)
print("Unix", UX)
print("Linux", LX)
print("--------------------")
print("CPU INFO: (BASIC)")
print("--------------------")
print("CPU CORE COUNT: ", CC)
print("CPU LOGICAL CORE COUNT: ", CCL)
print("PROCESS TIME: ", PT)
print("PROCESS TIME IN NS: ", PT2)
print("THREAD TIME IN NS: ", TTN)
print("--------------------")
print("OTHER INFO:")
print("--------------------")
print("PYTHON INFO: ",  SYS1)
print("DISK USAGE (Bytes): ", DU)
